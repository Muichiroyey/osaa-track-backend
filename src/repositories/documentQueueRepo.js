// Tri-state decision (spec section 21)
export async function decideTicket(id, action, { remarks } = {}) {
  // "approve" = approved for physical signing (the requester proceeds to
  // the office in person — this status/remarks pairing is what a future
  // student/alumni portal would read to tell them that directly).
  // "approve_esign" = approved for the e-signature workflow (admin adds
  // their own signature and can route to other offices from here).
  if (action === "approve") {
    // Approved for physical signing has no further in-app steps, so it
    // leaves the inbox immediately for the Queuing Archive's "Approved for
    // Physical Signing" box.
    const [result] = await pool.query(
      "UPDATE document_queue_tickets SET status='approved_for_signing', remarks=?, decided_at=NOW(), archived_at=NOW() WHERE id=?",
      [remarks || null, id]
    );
    return result.affectedRows > 0;
  }
  if (action === "approve_esign") {
    // Approved for e-signing still needs the admin to sign, possibly
    // route, then confirm — so it moves to the Document Queue's "Approved"
    // tab, not the archive, until confirmTicketSignature runs.
    const [result] = await pool.query(
      "UPDATE document_queue_tickets SET status='approved_for_esigning', remarks=?, decided_at=NOW() WHERE id=?",
      [remarks || null, id]
    );
    return result.affectedRows > 0;
  }
  if (action === "reject") {
    const [result] = await pool.query(
      "UPDATE document_queue_tickets SET status='rejected', remarks=?, decided_at=NOW(), archived_at=NOW() WHERE id=?",
      [remarks || null, id]
    );
    return result.affectedRows > 0;
  }
  if (action === "revise") {
    // Compliance window is admin-configurable from Settings (defaults to
    // 7 days per spec section 22). Ticket keeps its number. Moves to the
    // Queuing Archive's "Needs Revision" box right away — resubmitting
    // (below) pulls it back into the active Queuing tab and clears
    // archived_at again.
    const revisionDays = await getSettingInt("documentQueueRevisionDays", 7);
    const [result] = await pool.query(
      `UPDATE document_queue_tickets
       SET status='revision_requested', remarks=?, decided_at=NOW(), revision_deadline = NOW() + INTERVAL ? DAY, archived_at=NOW()
       WHERE id=?`,
      [remarks || null, revisionDays, id]
    );
    return result.affectedRows > 0;
  }
  throw new Error(`Unknown decision action: ${action}`);
}

// Requester re-uploads within the 7-day window — same ticket returns to
// the active Queuing tab (spec section 22, step 4-5), leaving the Needs
// Revision archive box since it clears archived_at.
export async function resubmitTicket(id) {
  const [result] = await pool.query(
    `UPDATE document_queue_tickets
     SET status='pending', revision_deadline=NULL, archived_at=NULL
     WHERE id=? AND status='revision_requested' AND revision_deadline >= NOW()`,
    [id]
  );
  return result.affectedRows > 0;
}

// Sweeps revision-requested tickets whose 7-day window has lapsed and
// expires them (spec section 22, step 6-7). Called opportunistically
// whenever the queue is listed, so nothing needs a background scheduler.
export async function expireOverdueRevisions() {
  const [result] = await pool.query(
    "UPDATE document_queue_tickets SET status='expired' WHERE status='revision_requested' AND revision_deadline < NOW()"
  );
  return result.affectedRows;
}

// Returns the document the NEXT signer should sign on top of.
//   • Once anyone has signed under the layered model, that is the ticket's
//     cumulative copy (signed_file_id) — it already carries every signature.
//   • A ticket signed before layers existed falls back to the old rule: the
//     last office's signed copy, else the admin's own, else the original.
export async function getLatestSignableFile(ticketId) {
  const ticket = await getTicket(ticketId);
  if (!ticket) return null;

  const [[{ layerCount }]] = await pool.query(
    "SELECT COUNT(*) AS layerCount FROM esignature_layers WHERE ticket_id = ?",
    [ticketId]
  );
  if (Number(layerCount) > 0 && ticket.signed_file_id) return ticket.signedFile;

  const [routeRows] = await pool.query(
    "SELECT signed_file_id FROM esignature_routes WHERE ticket_id = ? AND signed_file_id IS NOT NULL ORDER BY id DESC LIMIT 1",
    [ticketId]
  );
  if (routeRows[0]) return getFile(routeRows[0].signed_file_id);
  if (ticket.signed_file_id) return ticket.signedFile;
  return ticket.file || null;
}

