// Admin simulates the routed office adding their signature — the office's
// own panel doesn't exist yet, so this stands in for it, and it is written so
// the panel can call the very same function later. The signed copy already
// contains everything signed before it (it was made on top of the ticket's
// latest copy), so it does two things: it is the office's own snapshot, AND
// it becomes the ticket's cumulative copy — which is what makes this
// office's signature show up on the document the requester receives.
export async function signRoute(routeId, signedFileId, layer) {
  const route = await getRoute(routeId);
  if (!route) return false;
  await pool.query("UPDATE esignature_routes SET signed_file_id = ?, status = 'signed' WHERE id = ?", [signedFileId, routeId]);
  await pool.query("UPDATE document_queue_tickets SET signed_file_id = ? WHERE id = ?", [signedFileId, route.ticket_id]);
  await upsertLayer(route.ticket_id, { signerKey: routeSignerKey(routeId), routeId, layer });
  return true;
}

// The routed office (simulated, for now) confirms their signature is
// final — the admin sees this flip from "Pending" to "Done".
export async function confirmRoute(routeId) {
  const [result] = await pool.query(
    "UPDATE esignature_routes SET confirmed_at = NOW() WHERE id = ?",
    [routeId]
  );
  return result.affectedRows > 0;
}

// The admin's own final step: confirms their signature and releases the
// document to the requester (student/alumni). This is what moves a ticket
// out of the Document Queue's "Approved" tab and into the Queuing
// Archive's "Approved for E-Signing" box.
export async function confirmTicketSignature(ticketId) {
  const [result] = await pool.query(
    "UPDATE document_queue_tickets SET confirmed_at = NOW(), archived_at = NOW() WHERE id = ? AND signed_file_id IS NOT NULL AND signed_at IS NOT NULL",
    [ticketId]
  );
  return result.affectedRows > 0;
}


// ── SAA Staff Portal: forward to the SAA Dean ───────────────────────────
// Only a ticket that is genuinely waiting for a first decision (pending, has
// a document, not already forwarded) can be passed up. Returns true when it
// was forwarded now.
export async function forwardTicketToDean(id, staffUserId, note) {
  const [result] = await pool.query(
    `UPDATE document_queue_tickets
     SET forwarded_to_dean_at = NOW(), forwarded_by_user_id = ?, forward_note = ?
     WHERE id = ? AND status = 'pending' AND file_id IS NOT NULL AND forwarded_to_dean_at IS NULL`,
    [staffUserId, note ? String(note).trim() || null : null, id]
  );
  return result.affectedRows > 0;
}
