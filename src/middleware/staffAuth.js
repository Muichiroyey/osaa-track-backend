import { resolvePortalUser } from "./portalAuth.js";

/**
 * SAA STAFF SESSIONS
 * ───────────────────────────────────────────────────────────────────────
 * The SAA Staff Portal is a second face on the SAME admin modules, with less
 * power. So instead of copying ~20 controllers, every admin router is also
 * mounted under /api/staff (see routes/staff.routes.js) behind this one
 * gate. The gate:
 *
 *   1. accepts ONLY a valid portal session whose account is `users.type =
 *      'staff'` — a student / alumni / office token is refused (403), and the
 *      admin's own token is not a portal session at all, so it is refused (401);
 *   2. re-checks the account's status on every request (a deactivated staff
 *      account stops working immediately — resolvePortalUser does that);
 *   3. marks the request as `staffContext`, which makes the admin routers'
 *      own `requireAuth` step aside (see middleware/auth.js) and fills in
 *      `req.admin` with a staff-shaped identity, so the existing controllers
 *      that read `req.admin` (report "generated by", etc.) keep working.
 *
 * Staff sessions are the multi-session portal kind (not the admin's
 * single-device kind): several staff members are signed in at once, and
 * signing in as staff never kicks the admin out.
 */
export async function requireStaff(req, res, next) {
  const { user, token, error } = await resolvePortalUser(req);
  if (error) return res.status(error.status).json({ error: error.code, message: error.message });

  if (user.type !== "staff") {
    return res.status(403).json({
      error: "WRONG_ACCOUNT_TYPE",
      message: `This section is for SAA Staff accounts. You're signed in as ${user.type}.`,
    });
  }

  req.staffUser = user;
  req.staffToken = token;
  req.staffContext = true;
  // Shaped like the admin row the shared controllers expect.
  req.admin = {
    id: null,
    username: user.email,
    display_name: user.name,
    role: "staff",
    avatar_file_id: user.avatar_file_id || null,
  };
  next();
}

/** Fails a staff request for something the Dean (admin) alone may do. */
export function dean(message) {
  return (req, res) =>
    res.status(403).json({
      error: "DEAN_ONLY",
      message: message || "This action is reserved for the SAA Dean.",
    });
}
