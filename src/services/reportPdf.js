import PDFDocument from "pdfkit";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PH_TIME_ZONE } from "../config/timezone.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PSU_SEAL = path.join(__dirname, "..", "assets", "psu-seal.png");
const SAA_SEAL = path.join(__dirname, "..", "assets", "saa-seal.png");

export const COLORS = {
  indigo: "#312e81",
  indigoLight: "#4f46e5",
  // Brand navy/gold — matches the app's own sidebar gradient
  // (#1e1b4b → #312e81 → #3730a3) and header gold rail (#f5c800), so a
  // printed report reads as unmistakably OSAA-TRACK at a glance.
  navyBannerFrom: "#1e1b4b",
  navyBannerTo: "#3730a3",
  gold: "#f5c800",
  goldDark: "#d4a800",
  slate900: "#1e293b",
  slate700: "#334155",
  slate500: "#64748b",
  slate400: "#94a3b8",
  slate200: "#e2e8f0",
  slate100: "#f1f5f9",
  slate50: "#f8fafc",
  white: "#ffffff",
};

export const PAGE_MARGIN = 42;
const ROW_HEIGHT = 20;
const HEADER_ROW_HEIGHT = 28;

// Every timestamp printed on a generated PDF is shown in Philippine
// Standard Time (UTC+8) no matter where the server runs. Without an
// explicit timeZone, toLocaleString() uses the *server's* clock zone —
// fine on a Philippine laptop, but a cloud host like Railway runs in UTC,
// which made every PDF read 8 hours behind. Asia/Manila has no daylight
// saving, so this is always exactly UTC+8.
export { PH_TIME_ZONE };

export function formatDateTime(d) {
  return d.toLocaleString("en-US", {
    timeZone: PH_TIME_ZONE,
    month: "short",
    day: "numeric",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit",
  });
}

// Masthead used on every generated report — a full-width navy banner
// (matching the app's own sidebar gradient) with both university seals,
// a gold accent rail underneath, then the report's title/description and
// a "Generated / Generated by / Filters applied" info box. This is the
// standard header for every report type (table or individual-record).
export function drawBrandHeader(doc, { reportTitle, description, refNo, generatedBy, filtersSummary, generatedAt }) {
  const pageWidth = doc.page.width;
  const contentWidth = pageWidth - PAGE_MARGIN * 2;
  const bannerHeight = 88;
  const sealSize = 50;

  // ── navy banner with both seals ──────────────────────────────────
  const gradient = doc.linearGradient(0, 0, pageWidth, 0);
  gradient.stop(0, COLORS.navyBannerFrom).stop(1, COLORS.navyBannerTo);
  doc.rect(0, 0, pageWidth, bannerHeight).fill(gradient);
  doc.rect(0, bannerHeight, pageWidth, 4).fill(COLORS.gold);

  const sealY = (bannerHeight - sealSize) / 2;
  if (fs.existsSync(PSU_SEAL)) doc.image(PSU_SEAL, PAGE_MARGIN, sealY, { width: sealSize, height: sealSize });
  if (fs.existsSync(SAA_SEAL)) doc.image(SAA_SEAL, pageWidth - PAGE_MARGIN - sealSize, sealY, { width: sealSize, height: sealSize });

  const textInset = PAGE_MARGIN + sealSize + 24;
  const textWidth = pageWidth - textInset * 2;
  let ty = bannerHeight / 2 - 24;
  doc
    .fillColor(COLORS.gold)
    .font("Helvetica-Bold")
    .fontSize(9)
    .text("PANGASINAN STATE UNIVERSITY \u2014 LINGAYEN CAMPUS", textInset, ty, {
      align: "center",
      width: textWidth,
      characterSpacing: 0.6,
    });
  ty += 15;
  doc
    .fillColor(COLORS.white)
    .font("Helvetica-Bold")
    .fontSize(16)
    .text("Office of Student and Alumni Affairs", textInset, ty, { align: "center", width: textWidth });
  ty += 20;
  doc
    .fillColor("#c7d2fe")
    .font("Helvetica")
    .fontSize(8.5)
    .text("OSAA-TRACK \u00b7 Report Generation", textInset, ty, { align: "center", width: textWidth, characterSpacing: 0.4 });

  let y = bannerHeight + 4 + 22;

  // ── report title + reference number ──────────────────────────────
  doc.fillColor(COLORS.navyBannerFrom).font("Helvetica-Bold").fontSize(15).text(reportTitle, PAGE_MARGIN, y, { width: contentWidth - 140 });
  if (refNo) {
    doc
      .fillColor(COLORS.slate500)
      .font("Helvetica")
      .fontSize(8.5)
      .text(`Ref. No. ${refNo}`, PAGE_MARGIN, y + 2, { width: contentWidth, align: "right" });
  }
  y += 20;

  if (description) {
    doc.fillColor(COLORS.slate500).font("Helvetica").fontSize(9).text(description, PAGE_MARGIN, y, { width: contentWidth });
    y += doc.heightOfString(description, { width: contentWidth }) + 12;
  }

  // ── generated / generated-by / filters info box ──────────────────
  const infoLines = [
    `Generated: ${formatDateTime(generatedAt)}`,
    `Generated by: ${generatedBy || "OSAA-TRACK Admin"}`,
    `Filters applied: ${filtersSummary || "None \u2014 showing the full list"}`,
  ];
  const infoPad = 10;
  const infoHeight = infoPad * 2 + infoLines.length * 12;
  doc.roundedRect(PAGE_MARGIN, y, contentWidth, infoHeight, 6).fill(COLORS.slate50);
  doc.font("Helvetica").fontSize(8.5).fillColor(COLORS.slate700);
  infoLines.forEach((line, i) => {
    doc.text(line, PAGE_MARGIN + infoPad, y + infoPad + i * 12, { width: contentWidth - infoPad * 2, ellipsis: true });
  });
  y += infoHeight + 16;

  return y;
}

export function drawFooter(doc, pageIndex, pageCount) {
  const pageWidth = doc.page.width;
  const pageHeight = doc.page.height;
  const y = pageHeight - 30;
  doc.moveTo(PAGE_MARGIN, y).lineTo(pageWidth - PAGE_MARGIN, y).lineWidth(0.5).strokeColor(COLORS.slate200).stroke();
  // `lineBreak: false` on both calls below is required, not cosmetic: this
  // footer is drawn intentionally inside the bottom page margin. Without
  // it, pdfkit's default text-wrapping path auto-computes a width and,
  // seeing text placed past the margin boundary, silently appends a blank
  // extra page per call — two footer text calls meant two phantom trailing
  // pages tacked onto every single PDF this module generated. Disabling
  // line-wrapping skips that overflow check, which is safe here since
  // these are always short, fixed, single-line labels.
  doc
    .fillColor(COLORS.slate400)
    .font("Helvetica")
    .fontSize(7.5)
    .text("OSAA-TRACK \u2014 generated by the Admin Panel, for internal SAA use", PAGE_MARGIN, y + 8, {
      lineBreak: false,
    });
  // Right-aligned via a manual width calculation instead of {width, align}
  // -- passing an explicit `width` re-enables pdfkit's line-wrap engine
  // (and with it the margin-overflow check) regardless of lineBreak, so
  // right-alignment has to be done by hand to stay on the no-wrap path.
  const pageLabel = `Page ${pageIndex + 1} of ${pageCount}`;
  doc.font("Helvetica").fontSize(7.5);
  const pageLabelWidth = doc.widthOfString(pageLabel);
  doc
    .fillColor(COLORS.slate400)
    .text(pageLabel, pageWidth - PAGE_MARGIN - pageLabelWidth, y + 8, { lineBreak: false });
}

function drawTableHeaderRow(doc, y, columnsWithWidth, colX) {
  doc.rect(PAGE_MARGIN, y, doc.page.width - PAGE_MARGIN * 2, HEADER_ROW_HEIGHT).fill(COLORS.indigo);
  doc.font("Helvetica-Bold").fontSize(7.5).fillColor(COLORS.white);
  columnsWithWidth.forEach((col, i) => {
    // Long labels (e.g. "Scholarship / Category") wrap to a second line
    // rather than getting ellipsis-truncated, matching how the university
    // masthead template wraps its own column headers.
    doc.text(col.label.toUpperCase(), colX[i] + 8, y + 5, {
      width: col.width - 14,
      height: HEADER_ROW_HEIGHT - 6,
      characterSpacing: 0.3,
      lineGap: 1,
    });
  });
  return y + HEADER_ROW_HEIGHT;
}

/**
 * Renders a branded, paginated table report to a PDF file on disk.
 *
 * @param {object} opts
 * @param {string} opts.reportTitle
 * @param {string|null} [opts.filtersSummary]
 * @param {{key:string,label:string,weight?:number}[]} opts.columns
 * @param {object[]} opts.rows - plain objects keyed by each column's `key`
 * @param {Date} [opts.generatedAt]
 * @param {boolean} [opts.landscape] - use landscape orientation (for 6+ columns)
 * @param {string} outPath - absolute path to write the PDF to
 * @returns {Promise<string>} resolves with outPath once the file is written
 */
export function buildTableReportPdf(
  {
    reportTitle,
    description = null,
    refNo = null,
    generatedBy = null,
    filtersSummary = null,
    columns,
    rows,
    generatedAt = new Date(),
    landscape = false,
  },
  outPath
) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "LETTER",
      layout: landscape ? "landscape" : "portrait",
      margins: { top: PAGE_MARGIN, bottom: PAGE_MARGIN, left: PAGE_MARGIN, right: PAGE_MARGIN },
      bufferPages: true,
      info: { Title: reportTitle, Author: "OSAA-TRACK Admin Panel" },
    });
    const stream = fs.createWriteStream(outPath);
    doc.pipe(stream);

    const contentWidth = doc.page.width - PAGE_MARGIN * 2;
    const totalWeight = columns.reduce((sum, c) => sum + (c.weight || 1), 0);
    const colWidths = columns.map((c) => ((c.weight || 1) / totalWeight) * contentWidth);
    const colX = [];
    let cursor = PAGE_MARGIN;
    colWidths.forEach((w) => {
      colX.push(cursor);
      cursor += w;
    });
    const columnsWithWidth = columns.map((c, i) => ({ ...c, width: colWidths[i] }));

    const headerOpts = { reportTitle, description, refNo, generatedBy, filtersSummary, generatedAt };
    let y = drawBrandHeader(doc, headerOpts);
    y = drawTableHeaderRow(doc, y, columnsWithWidth, colX);

    const bottomLimit = doc.page.height - PAGE_MARGIN - 26;

    if (rows.length === 0) {
      doc
        .font("Helvetica")
        .fontSize(9.5)
        .fillColor(COLORS.slate400)
        .text("No records match the selected filters.", PAGE_MARGIN, y + 16, { width: contentWidth, align: "center" });
    }

    rows.forEach((row, rIdx) => {
      if (y + ROW_HEIGHT > bottomLimit) {
        doc.addPage();
        y = drawBrandHeader(doc, headerOpts);
        y = drawTableHeaderRow(doc, y, columnsWithWidth, colX);
      }
      if (rIdx % 2 === 1) {
        doc.rect(PAGE_MARGIN, y, contentWidth, ROW_HEIGHT).fill(COLORS.slate50);
      }
      doc.font("Helvetica").fontSize(8.5).fillColor(COLORS.slate700);
      columnsWithWidth.forEach((col, i) => {
        const val = row[col.key];
        doc.text(val === null || val === undefined || val === "" ? "\u2014" : String(val), colX[i] + 8, y + 6, {
          width: col.width - 14,
          height: ROW_HEIGHT - 8,
          ellipsis: true,
        });
      });
      doc
        .moveTo(PAGE_MARGIN, y + ROW_HEIGHT)
        .lineTo(PAGE_MARGIN + contentWidth, y + ROW_HEIGHT)
        .lineWidth(0.5)
        .strokeColor(COLORS.slate100)
        .stroke();
      y += ROW_HEIGHT;
    });

    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      drawFooter(doc, i, range.count);
    }

    doc.end();
    stream.on("finish", () => resolve(outPath));
    stream.on("error", reject);
  });
}

// ── individual record report (single-student "application"/record sheet) ─

const STATUS_TONE_COLORS = {
  success: { bg: "#dcfce7", text: "#166534" },
  warning: { bg: "#fef3c7", text: "#92400e" },
  danger: { bg: "#fee2e2", text: "#991b1b" },
  neutral: { bg: "#e2e8f0", text: "#475569" },
};

function drawStatusPill(doc, rightX, y, label, tone) {
  const colors = STATUS_TONE_COLORS[tone] || STATUS_TONE_COLORS.neutral;
  const text = String(label || "").toUpperCase();
  doc.font("Helvetica-Bold").fontSize(8);
  const textWidth = doc.widthOfString(text);
  const pillWidth = textWidth + 20;
  const pillHeight = 18;
  const x = rightX - pillWidth;
  doc.roundedRect(x, y, pillWidth, pillHeight, 9).fill(colors.bg);
  doc.fillColor(colors.text).text(text, x, y + 5.5, { width: pillWidth, align: "center", characterSpacing: 0.4 });
}

function drawSectionTitle(doc, y, contentWidth, title) {
  doc.fillColor(COLORS.indigo).font("Helvetica-Bold").fontSize(9.5).text(title.toUpperCase(), PAGE_MARGIN, y, { characterSpacing: 0.4 });
  const lineY = y + 14;
  doc.moveTo(PAGE_MARGIN, lineY).lineTo(PAGE_MARGIN + contentWidth, lineY).lineWidth(1).strokeColor(COLORS.indigo).opacity(0.25).stroke();
  doc.opacity(1);
  return lineY + 12;
}

// Renders one section's fields as a 2-column label/value grid, with any
// field marked `long: true` (e.g. a description) breaking out to its own
// full-width paragraph row instead of sharing the grid.
function drawFieldGrid(doc, y, contentWidth, fields) {
  const colGap = 24;
  const colWidth = (contentWidth - colGap) / 2;
  const labelHeight = 11;
  let col = 0;
  let rowTop = y;
  let rowMaxHeight = 0;

  fields.forEach((field) => {
    const value = field.value === null || field.value === undefined || field.value === "" ? "\u2014" : String(field.value);

    if (field.long) {
      if (col === 1) {
        y = rowTop + rowMaxHeight + 10;
        col = 0;
        rowMaxHeight = 0;
      }
      doc.fillColor(COLORS.slate400).font("Helvetica-Bold").fontSize(7.5).text(field.label.toUpperCase(), PAGE_MARGIN, y, { characterSpacing: 0.5 });
      const valueY = y + labelHeight;
      doc.fillColor(COLORS.slate700).font("Helvetica").fontSize(9.5).text(value, PAGE_MARGIN, valueY, { width: contentWidth, lineGap: 2 });
      const valueHeight = doc.heightOfString(value, { width: contentWidth, lineGap: 2 });
      y = valueY + valueHeight + 12;
      rowTop = y;
      rowMaxHeight = 0;
      return;
    }

    const x = PAGE_MARGIN + col * (colWidth + colGap);
    doc.fillColor(COLORS.slate400).font("Helvetica-Bold").fontSize(7.5).text(field.label.toUpperCase(), x, rowTop, { width: colWidth, characterSpacing: 0.5 });
    const valueY = rowTop + labelHeight;
    doc.fillColor(COLORS.slate700).font("Helvetica-Bold").fontSize(9.5).text(value, x, valueY, { width: colWidth, lineGap: 1 });
    const valueHeight = doc.heightOfString(value, { width: colWidth, lineGap: 1 });
    rowMaxHeight = Math.max(rowMaxHeight, labelHeight + valueHeight);

    if (col === 1) {
      y = rowTop + rowMaxHeight + 10;
      rowTop = y;
      rowMaxHeight = 0;
      col = 0;
    } else {
      col = 1;
    }
  });

  if (col === 1) {
    y = rowTop + rowMaxHeight + 10;
  }
  return y;
}

/**
 * Renders a branded, single-record "application"/profile sheet — used for
 * an individual scholarship application or an individual achievement
 * submission, picked out by the admin from Report Generation. Shares the
 * same masthead as the table reports for a consistent look across every
 * PDF the module produces.
 *
 * @param {object} opts
 * @param {string} opts.reportTitle
 * @param {string} [opts.kicker] - small label above the heading
 * @param {string} opts.heading - the record's headline (usually the student's name)
 * @param {string|null} [opts.subheading]
 * @param {{label:string, tone:'success'|'warning'|'danger'|'neutral'}|null} [opts.status]
 * @param {{title:string, fields:{label:string,value:any,long?:boolean}[]}[]} opts.sections
 * @param {{title:string, items:string[]}|null} [opts.listSection]
 * @param {{original_name?:string, originalName?:string}[]} [opts.files]
 * @param {{title:string, body:string}|null} [opts.note]
 * @param {Date} [opts.generatedAt]
 * @param {string} outPath
 */
export function buildIndividualRecordPdf(
  {
    reportTitle,
    description = null,
    refNo = null,
    generatedBy = null,
    kicker = null,
    heading,
    subheading = null,
    status = null,
    sections = [],
    listSection = null,
    files = [],
    note = null,
    generatedAt = new Date(),
  },
  outPath
) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "LETTER",
      layout: "portrait",
      margins: { top: PAGE_MARGIN, bottom: PAGE_MARGIN, left: PAGE_MARGIN, right: PAGE_MARGIN },
      bufferPages: true,
      info: { Title: `${reportTitle} - ${heading}`, Author: "OSAA-TRACK Admin Panel" },
    });
    const stream = fs.createWriteStream(outPath);
    doc.pipe(stream);

    const contentWidth = doc.page.width - PAGE_MARGIN * 2;
    const headerOpts = {
      reportTitle,
      description,
      refNo,
      generatedBy,
      filtersSummary: "Single record, selected by the admin",
      generatedAt,
    };
    const bottomLimit = doc.page.height - PAGE_MARGIN - 26;

    function ensureSpace(currentY, needed) {
      if (currentY + needed > bottomLimit) {
        doc.addPage();
        return drawBrandHeader(doc, headerOpts);
      }
      return currentY;
    }

    let y = drawBrandHeader(doc, headerOpts);

    // ── heading card ──────────────────────────────────────────────────
    const cardPad = 16;
    const headingWidth = contentWidth - cardPad * 2 - 90;
    doc.font("Helvetica-Bold").fontSize(16);
    const headingHeight = doc.heightOfString(heading, { width: headingWidth });
    let cardHeight = cardPad * 2 + headingHeight;
    if (kicker) cardHeight += 13;
    if (subheading) cardHeight += 14;

    y = ensureSpace(y, cardHeight + 16);
    doc.roundedRect(PAGE_MARGIN, y, contentWidth, cardHeight, 10).fill(COLORS.slate50);
    doc.rect(PAGE_MARGIN, y, 4, cardHeight).fill(COLORS.indigo);

    let ty = y + cardPad;
    if (kicker) {
      doc.fillColor(COLORS.indigoLight).font("Helvetica-Bold").fontSize(8).text(kicker.toUpperCase(), PAGE_MARGIN + cardPad, ty, { characterSpacing: 0.6 });
      ty += 13;
    }
    doc.fillColor(COLORS.slate900).font("Helvetica-Bold").fontSize(16).text(heading, PAGE_MARGIN + cardPad, ty, { width: headingWidth });
    ty += headingHeight;
    if (subheading) {
      doc.fillColor(COLORS.slate500).font("Helvetica").fontSize(9).text(subheading, PAGE_MARGIN + cardPad, ty, { width: headingWidth });
    }
    if (status) {
      drawStatusPill(doc, PAGE_MARGIN + contentWidth - cardPad, y + cardPad, status.label, status.tone);
    }
    y += cardHeight + 22;

    // ── sections ──────────────────────────────────────────────────────
    sections.forEach((section) => {
      y = ensureSpace(y, 40);
      y = drawSectionTitle(doc, y, contentWidth, section.title);
      y = drawFieldGrid(doc, y, contentWidth, section.fields || []);
      y += 14;
    });

    // ── optional checklist section (e.g. required documents) ───────────
    if (listSection && listSection.items && listSection.items.length) {
      y = ensureSpace(y, 40);
      y = drawSectionTitle(doc, y, contentWidth, listSection.title);
      doc.font("Helvetica").fontSize(9.5).fillColor(COLORS.slate700);
      listSection.items.forEach((item) => {
        const itemHeight = doc.heightOfString(item, { width: contentWidth - 16 });
        y = ensureSpace(y, itemHeight + 8);
        doc.fillColor(COLORS.indigoLight).text("\u2022", PAGE_MARGIN, y, { width: 12 });
        doc.fillColor(COLORS.slate700).text(item, PAGE_MARGIN + 14, y, { width: contentWidth - 14 });
        y += itemHeight + 6;
      });
      y += 8;
    }

    // ── attachments ──────────────────────────────────────────────────
    if (files && files.length) {
      y = ensureSpace(y, 40);
      y = drawSectionTitle(doc, y, contentWidth, "Attachments on File");
      doc.font("Helvetica").fontSize(9).fillColor(COLORS.slate700);
      files.forEach((f) => {
        const name = f.original_name || f.originalName || "Untitled file";
        y = ensureSpace(y, 18);
        doc.fillColor(COLORS.slate400).text("\u2013", PAGE_MARGIN, y, { width: 12 });
        doc.fillColor(COLORS.slate700).text(name, PAGE_MARGIN + 14, y, { width: contentWidth - 14, ellipsis: true });
        y += 16;
      });
      y += 8;
    }

    // ── note callout (e.g. rejection reason) ───────────────────────────
    if (note && note.body) {
      const noteWidth = contentWidth - 28;
      doc.font("Helvetica").fontSize(9);
      const bodyHeight = doc.heightOfString(note.body, { width: noteWidth });
      const noteHeight = bodyHeight + 34;
      y = ensureSpace(y, noteHeight + 14);
      doc.roundedRect(PAGE_MARGIN, y, contentWidth, noteHeight, 8).fill("#fef2f2");
      doc.rect(PAGE_MARGIN, y, 4, noteHeight).fill("#dc2626");
      doc.fillColor("#991b1b").font("Helvetica-Bold").fontSize(8.5).text(note.title.toUpperCase(), PAGE_MARGIN + 14, y + 10, { characterSpacing: 0.4 });
      doc.fillColor("#7f1d1d").font("Helvetica").fontSize(9).text(note.body, PAGE_MARGIN + 14, y + 22, { width: noteWidth });
      y += noteHeight + 18;
    }

    // ── certification / signature footer ───────────────────────────────
    y = ensureSpace(y, 70);
    doc.moveTo(PAGE_MARGIN, y).lineTo(PAGE_MARGIN + contentWidth, y).lineWidth(0.75).strokeColor(COLORS.slate200).stroke();
    y += 12;
    doc
      .fillColor(COLORS.slate400)
      .font("Helvetica-Oblique")
      .fontSize(8)
      .text(`This record reflects OSAA-TRACK data on file as of ${formatDateTime(generatedAt)}.`, PAGE_MARGIN, y, { width: contentWidth });
    y += 26;

    const sigColWidth = (contentWidth - 24) / 2;
    [
      { x: PAGE_MARGIN, label: "Prepared by (OSAA representative)" },
      { x: PAGE_MARGIN + sigColWidth + 24, label: "Date" },
    ].forEach(({ x, label }) => {
      doc.moveTo(x, y).lineTo(x + sigColWidth, y).lineWidth(0.75).strokeColor(COLORS.slate400).stroke();
      doc.fillColor(COLORS.slate400).font("Helvetica").fontSize(7.5).text(label, x, y + 4, { width: sigColWidth });
    });

    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      drawFooter(doc, i, range.count);
    }

    doc.end();
    stream.on("finish", () => resolve(outPath));
    stream.on("error", reject);
  });
}
